// Live-stack check; creates one isolated customer and debits PHP 3 from its welcome balance.
const assert = require('node:assert/strict');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  const browser = await chromium.launch({channel:'chrome',headless:true});
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1000}});
    const errors=[]; page.on('pageerror',e=>errors.push(e.message));
    const base='http://localhost:3001/api/v1/auth/banking';
    const username=`external_${Date.now()}`;
    const registered=await page.request.post(base+'/register',{data:{username,password:'External-test-123',firstName:'External',lastName:'Tester',email:username+'@example.com',phone:'+639171234567'}});
    assert.equal(registered.status(),201,await registered.text());
    const session=await registered.json();
    const headers={Authorization:`Bearer ${session.token}`};
    await page.goto('http://localhost:3001/bank/');
    await page.evaluate(s=>sessionStorage.setItem('paypink.customer.session',JSON.stringify({token:s.token,fullName:s.fullName,expiresAt:Date.now()+s.expiresInMs})),session);
    await page.reload(); await page.locator('.account-card').first().waitFor();
    await page.locator('[data-page="transfer"]').first().click();
    await page.locator('[data-mode="external"]').click();
    assert.equal(await page.locator('#external-name').inputValue(),'');
    assert.equal(await page.locator('#external-recipient').evaluate(e=>e.tagName),'INPUT');
    assert.doesNotMatch(await page.locator('main').innerText(),/mock|simulation|demo/i);
    await page.locator('#external-recipient').fill('001234567890');
    assert.equal(await page.locator('#external-name').inputValue(),'Alex Reyes');
    await page.locator('#external-recipient').fill('000000000000');
    assert.equal(await page.locator('#external-name').inputValue(),'');
    assert.equal(await page.locator('#external-recipient').evaluate(e=>e.tagName),'INPUT');
    assert.doesNotMatch(await page.locator('main').innerText(),/mock|simulation|demo/i);
    await page.locator('#external-recipient').fill('001234567890');
    await page.locator('#transfer-amount').fill('1');
    await page.getByRole('button',{name:'Review transfer',exact:true}).click();
    await page.getByRole('button',{name:'Confirm transfer',exact:true}).click();
    await page.getByRole('heading',{name:'Transfer completed'}).waitFor();
    console.log('InstaPay completed synchronously');
    await page.getByRole('button',{name:'Done',exact:true}).click();
    await page.locator('[data-mode="external"]').click();
    await page.locator('#external-rail').selectOption('PESONET');
    await page.locator('#external-recipient').fill('009876543210');
    assert.equal(await page.locator('#external-name').inputValue(),'Jamie Santos');
    await page.locator('#transfer-amount').fill('2');
    await page.getByRole('button',{name:'Review transfer',exact:true}).click();
    await page.getByRole('button',{name:'Confirm transfer',exact:true}).click();
    await page.getByRole('heading',{name:'Waiting for the PESONet batch'}).waitFor();
    const profile=await (await page.request.get(base+'/me',{headers})).json();
    assert.equal(profile.accounts.find(a=>a.accountType==='EVERYDAY_ACCOUNT').currentBalance,49);
    let rows=await (await page.request.get(base+'/external/transfers',{headers})).json();
    assert.equal(rows.length,2); assert.equal(rows[0].status,'PENDING');
    const reference=rows[0].reference;
    console.log('PESONet pending; balance unchanged until processing');
    await page.reload(); await page.locator('.account-card').first().waitFor();
    await page.locator('[data-page="transfer"]').first().click();await page.locator('[data-mode="external"]').click();
    await page.locator(`[data-external-receipt="${reference}"]`).waitFor();
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await page.locator(`[data-external-receipt="${reference}"]`).click();
    await page.getByRole('heading',{name:'Waiting for the PESONet batch'}).waitFor();
    await page.getByRole('heading',{name:'Transfer completed'}).waitFor({timeout:110000});
    rows=await (await page.request.get(base+'/external/transfers',{headers})).json();
    assert.equal(rows.find(r=>r.reference===reference).status,'COMPLETED');
    const completedProfile=await (await page.request.get(base+'/me',{headers})).json();
    assert.equal(completedProfile.accounts.find(a=>a.accountType==='EVERYDAY_ACCOUNT').currentBalance,47);
    const activity=await (await page.request.get(base+'/transactions',{headers})).json();
    assert.equal(activity.find(t=>t.reference===reference).counterpartyName,'Jamie Santos');
    assert.equal(activity.find(t=>t.reference===reference).status,'SUCCESS');
    assert.deepEqual(errors,[]);
    console.log('PASS: durable pending status, automatic batch completion, recipient history, responsive UI');
  } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exit(1)});
